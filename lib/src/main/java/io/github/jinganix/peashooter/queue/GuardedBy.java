package io.github.jinganix.peashooter.queue;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Declares the monitor guarding a field or method.
 *
 * <p>Local equivalent of the JCIP annotation without a new dependency: the value names the holding
 * monitor (here always {@code "lock"}, the queue's dedicated monitor).
 */
@Documented
@Retention(RetentionPolicy.CLASS)
@Target({ElementType.FIELD, ElementType.METHOD})
@interface GuardedBy {
  String value();
}
